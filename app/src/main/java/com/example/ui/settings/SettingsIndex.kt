/** Lower case without accents, so "camera" finds "Câmera" and "agua" finds "Marca d'água". */
fun searchable(text: String): String =
    Normalizer.normalize(text, Normalizer.Form.NFD).replace(Regex("\\p{M}+"), "").lowercase()

/** What [query] finds in [section]: matched row titles, or the page name itself; null when nothing. */
fun settingsMatches(section: SettingsSection, query: String): List<String>? {
    val words = searchable(query).split(' ').filter { it.isNotBlank() }
    if (words.isEmpty()) return emptyList()
    fun hit(text: String) = searchable(text).let { t -> words.all { it in t } }
    val rows = settingsIndex[section].orEmpty().filter(::hit)
    return when {
        rows.isNotEmpty() -> rows
        hit(section.title) || hit(section.summary) -> emptyList()
        else -> null
    }
}
