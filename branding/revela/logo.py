"""
Revela logo: a print's frame with a half disc of light rising from its bottom edge, the picture
"developing" on the paper. One geometry (100 x 100 units) -> every format the app needs.

Run: python3 branding/revela/logo.py  (needs Pillow for the PNG/WebP icons and the preview)
Writes the Android resources into app/src/revela/res and an SVG + preview next to this file.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "app", "src", "revela", "res")

INK = "#110F0D"        # darkroom black
PAPER = "#F2EBE0"      # paper
LIGHT = "#FF7A3D"      # safelight

# Geometry, 100 x 100 units.
OUT = (16, 20, 84, 80, 8)   # outer frame x0, y0, x1, y1, radius
INN = (23, 27, 77, 73, 3)   # inner edge of the frame (frame 7 units thick)
DISC = (50, 73, 17)         # centre x, centre y (on the inner bottom edge), radius

def rrect(x0, y0, x1, y1, r):
    return (f"M{x0+r},{y0} L{x1-r},{y0} Q{x1},{y0} {x1},{y0+r} L{x1},{y1-r} Q{x1},{y1} {x1-r},{y1} "
            f"L{x0+r},{y1} Q{x0},{y1} {x0},{y1-r} L{x0},{y0+r} Q{x0},{y0} {x0+r},{y0} Z")

FRAME = rrect(*OUT) + " " + rrect(*INN)
cx, cy, r = DISC
SUN = f"M{cx-r},{cy} A{r},{r} 0 0,1 {cx+r},{cy} Z"

def vector(size_dp, viewport, scale, offset, frame_color, sun_color, comment, bg=None):
    group = f'<group android:scaleX="{scale}" android:scaleY="{scale}" android:translateX="{offset}" android:translateY="{offset}">'
    bgp = f'\n    <path android:fillColor="{bg}" android:pathData="M0,0h{viewport}v{viewport}h-{viewport}z" />' if bg else ""
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by branding/revela/logo.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp" android:height="{size_dp}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">{bgp}
    {group}
        <path android:fillColor="{frame_color}" android:fillType="evenOdd" android:pathData="{FRAME}" />
        <path android:fillColor="{sun_color}" android:pathData="{SUN}" />
    </group>
</vector>
'''

def write(rel, text):
    path = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)

def main():
    # Adaptive icon: 108 dp canvas, the mark kept well inside the 66 dp safe circle.
    write("drawable/ic_launcher_foreground.xml", vector(108, 108, 0.62, 23, PAPER, LIGHT, "Revela launcher mark."))
    write("drawable/ic_launcher_monochrome.xml", vector(108, 108, 0.62, 23, "#FFFFFFFF", "#FFFFFFFF", "Revela themed-icon mark."))
    write("drawable/ic_launcher_background.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Darkroom black. Generated by branding/revela/logo.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{INK}" android:pathData="M0,0h108v108h-108z" />
</vector>
''')
    # Notification icon (white only) and the in-app mark (paper + safelight).
    write("drawable/ic_stat_symbol.xml", vector(24, 24, 0.27, -1.5, "#FFFFFFFF", "#FFFFFFFF", "Revela notification mark."))
    write("drawable/ic_brand_symbol.xml", vector(48, 100, 1.4, -20, PAPER, LIGHT, "Revela mark, frame and rising light."))
    # SVG master for docs and print.
    with open(os.path.join(HERE, "revela_mark.svg"), "w") as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" rx="22" fill="{INK}"/>'
                f'<path fill="{PAPER}" fill-rule="evenodd" d="{FRAME}"/><path fill="{LIGHT}" d="{SUN}"/></svg>\n')
    try:
        raster()
    except ImportError:
        print("Pillow not installed: vector resources written, PNG/WebP icons skipped.")

def draw_mark(size, bg=True, pad=0.0):
    from PIL import Image, ImageDraw
    s = 4  # supersample
    W = size * s
    img = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if bg:
        d.rounded_rectangle([0, 0, W - 1, W - 1], radius=int(W * 0.22), fill=INK)
    k = W / 100 * (1 - 2 * pad)
    o = W * pad
    t = lambda v: o + v * k
    x0, y0, x1, y1, rr = OUT
    d.rounded_rectangle([t(x0), t(y0), t(x1), t(y1)], radius=rr * k, fill=PAPER)
    x0, y0, x1, y1, rr = INN
    d.rounded_rectangle([t(x0), t(y0), t(x1), t(y1)], radius=rr * k, fill=INK if bg else (0, 0, 0, 0))
    d.pieslice([t(cx - r), t(cy - r), t(cx + r), t(cy + r)], 180, 360, fill=LIGHT)
    return img.resize((size, size), Image.LANCZOS)

def raster():
    # Legacy launcher icons for Android 7 (the adaptive icon covers 8+).
    for name, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        img = draw_mark(px, bg=True, pad=0.08)
        os.makedirs(os.path.join(RES, f"mipmap-{name}"), exist_ok=True)
        img.save(os.path.join(RES, f"mipmap-{name}", "ic_launcher.webp"), "WEBP", lossless=True)
        img.save(os.path.join(RES, f"mipmap-{name}", "ic_launcher_round.webp"), "WEBP", lossless=True)
    draw_mark(512, bg=True, pad=0.06).save(os.path.join(HERE, "revela_icon_512.png"))

if __name__ == "__main__":
    main()
