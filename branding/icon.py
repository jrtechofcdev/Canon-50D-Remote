"""
App icon for JR C50D Sync: a camera in the Jr_Tech_OFC mint→cyan gradient whose lens is two sync
arrows (tethered capture). The prism on top is a slanted block like the tiles of the brand symbol.
Writes the adaptive-icon vectors, the legacy WebP launchers and a preview PNG.

    python3 branding/icon.py
"""
import math
import os
from PIL import Image, ImageDraw

MINT = (0x00, 0xFC, 0xA8)
CYAN = (0x1C, 0xDA, 0xFF)
GRAPHITE = (0x29, 0x29, 0x29)

# Geometry in the 108 × 108 adaptive-icon viewport (safe zone: circle of radius 33 around 54,54).
BODY = (26.0, 40.0, 82.0, 77.0, 8.0)          # left, top, right, bottom, corner radius
PRISM = [(45.0, 30.5), (67.0, 30.5), (64.0, 41.5), (42.0, 41.5)]  # slanted like the brand tiles
SHUTTER = (30.0, 35.0, 38.0, 41.0, 1.6)
LENS = (54.0, 58.5, 12.8)                     # centre x, y, hole radius
LAMP = (74.5, 46.5, 2.2)
ARC_R = 7.6
ARC_W = 2.8
# Two arrows chasing each other around the lens: angles in degrees, 0 = right, counter-clockwise in math terms.
ARCS = [(200.0, 318.0), (20.0, 138.0)]


def pt(cx, cy, r, deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy - r * math.sin(a)


def arrow_head(cx, cy, r, deg, size=5.2):
    """Triangle at the end of an arc drawn counter-clockwise (math angles), pointing along the arc."""
    a = math.radians(deg)
    ex, ey = pt(cx, cy, r, deg)
    tx, ty = -math.sin(a), -math.cos(a)         # direction of travel at the arc's end (screen coords)
    nx, ny = math.cos(a), -math.sin(a)          # outward normal (screen coords)
    tip = (ex + tx * size, ey + ty * size)
    left = (ex + nx * size * 0.62, ey + ny * size * 0.62)
    right = (ex - nx * size * 0.62, ey - ny * size * 0.62)
    return [tip, left, right]


# ---------- Android vectors ----------

def rrect_path(l, t, r, b, rad):
    return ("M%.2f,%.2f L%.2f,%.2f Q%.2f,%.2f %.2f,%.2f L%.2f,%.2f Q%.2f,%.2f %.2f,%.2f "
            "L%.2f,%.2f Q%.2f,%.2f %.2f,%.2f L%.2f,%.2f Q%.2f,%.2f %.2f,%.2f Z") % (
        l + rad, t, r - rad, t, r, t, r, t + rad, r, b - rad, r, b, r - rad, b,
        l + rad, b, l, b, l, b - rad, l, t + rad, l, t, l + rad, t)


def poly_path(points):
    return "M" + " L".join("%.2f,%.2f" % p for p in points) + " Z"


def circle_path(cx, cy, r):
    return "M%.2f,%.2f A%.2f,%.2f 0 1,0 %.2f,%.2f A%.2f,%.2f 0 1,0 %.2f,%.2f Z" % (cx - r, cy, r, r, cx + r, cy, r, r, cx - r, cy)


def arc_path(cx, cy, r, a0, a1):
    x0, y0 = pt(cx, cy, r, a0)
    x1, y1 = pt(cx, cy, r, a1)
    # Counter-clockwise in math = sweep-flag 0 in screen coordinates.
    return "M%.2f,%.2f A%.2f,%.2f 0 0,0 %.2f,%.2f" % (x0, y0, r, r, x1, y1)


GRADIENT = '''<aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="26" android:startY="30" android:endX="82" android:endY="78">
                    <item android:offset="0" android:color="#FF00FCA8" />
                    <item android:offset="1" android:color="#FF1CDAFF" />
                </gradient>
            </aapt:attr>'''
STROKE_GRADIENT = GRADIENT.replace("android:fillColor", "android:strokeColor")


def vectors():
    l, t, r, b, rad = BODY
    sl, st, sr, sb, srad = SHUTTER
    cx, cy, hole = LENS
    body = rrect_path(l, t, r, b, rad)
    # Prism and shutter overlap the body, so they are separate paths (evenOdd would cut the overlap out).
    extras = [poly_path(PRISM), rrect_path(sl, st, sr, sb, srad)]
    holes = circle_path(cx, cy, hole) + " " + circle_path(*LAMP)
    arcs = [arc_path(cx, cy, ARC_R, a0, a1) for a0, a1 in ARCS]
    heads = [poly_path(arrow_head(cx, cy, ARC_R, a1)) for _, a1 in ARCS]
    header = ('<?xml version="1.0" encoding="utf-8"?>\n'
              '<!-- JR C50D Sync: camera with sync arrows as the lens, generated by branding/icon.py. -->\n'
              '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
              '    xmlns:aapt="http://schemas.android.com/aapt"\n'
              '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')
    # Colour: gradient body with the lens and lamp cut out (evenOdd), gradient arrows inside the lens.
    colour = header
    colour += '    <path android:fillType="evenOdd" android:pathData="%s %s">\n            %s\n    </path>\n' % (body, holes, GRADIENT)
    for e in extras:
        colour += '    <path android:pathData="%s">\n            %s\n    </path>\n' % (e, GRADIENT)
    for a in arcs:
        colour += ('    <path android:pathData="%s" android:strokeWidth="%.2f" android:strokeLineCap="round">\n'
                   '            %s\n    </path>\n') % (a, ARC_W, STROKE_GRADIENT)
    for h in heads:
        colour += '    <path android:pathData="%s">\n            %s\n    </path>\n' % (h, GRADIENT)
    colour += "</vector>\n"
    mono = header
    mono += '    <path android:fillType="evenOdd" android:fillColor="#FFFFFFFF" android:pathData="%s %s" />\n' % (body, holes)
    for e in extras:
        mono += '    <path android:fillColor="#FFFFFFFF" android:pathData="%s" />\n' % e
    for a in arcs:
        mono += '    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="%.2f" android:strokeLineCap="round" android:pathData="%s" />\n' % (ARC_W, a)
    for h in heads:
        mono += '    <path android:fillColor="#FFFFFFFF" android:pathData="%s" />\n' % h
    mono += "</vector>\n"
    return colour, mono


# ---------- Raster (legacy launchers, preview) ----------

def gradient_image(size, scale):
    img = Image.new("RGB", (size, size))
    px = img.load()
    x0, y0, x1, y1 = 26 * scale, 30 * scale, 82 * scale, 78 * scale
    dx, dy = x1 - x0, y1 - y0
    den = dx * dx + dy * dy
    for y in range(size):
        for x in range(size):
            t = max(0.0, min(1.0, ((x - x0) * dx + (y - y0) * dy) / den))
            px[x, y] = tuple(int(MINT[i] + (CYAN[i] - MINT[i]) * t) for i in range(3))
    return img


def render(size_px, shape="square"):
    """Icon as the launcher shows it: graphite background (rounded square or circle), mark in the middle."""
    ss = 4
    big = size_px * ss
    scale = big / 108.0
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    bg = ImageDraw.Draw(img)
    if shape == "circle":
        bg.ellipse([0, 0, big - 1, big - 1], fill=GRAPHITE + (255,))
    else:
        bg.rounded_rectangle([0, 0, big - 1, big - 1], radius=int(big * 0.22), fill=GRAPHITE + (255,))
    # Legacy icons have no mask margin: shrink the 108 viewport so the mark fills like the adaptive one.
    zoom = 108 / 76.0
    s = scale * zoom
    off = -(54 * s) + big / 2

    def P(x, y):
        return (x * s + off, y * s + off)

    mask = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(mask)
    l, t, r, b, rad = BODY
    d.rounded_rectangle([*P(l, t), *P(r, b)], radius=rad * s, fill=255)
    d.polygon([P(*p) for p in PRISM], fill=255)
    sl, st, sr, sb, srad = SHUTTER
    d.rounded_rectangle([*P(sl, st), *P(sr, sb)], radius=srad * s, fill=255)
    cx, cy, hole = LENS
    d.ellipse([*P(cx - hole, cy - hole), *P(cx + hole, cy + hole)], fill=0)
    lx, ly, lr = LAMP
    d.ellipse([*P(lx - lr, ly - lr), *P(lx + lr, ly + lr)], fill=0)
    for a0, a1 in ARCS:
        box = [*P(cx - ARC_R, cy - ARC_R), *P(cx + ARC_R, cy + ARC_R)]
        # PIL angles go clockwise from 3 o'clock: math angle a → PIL −a.
        d.arc(box, start=-a1, end=-a0, fill=255, width=max(1, int(ARC_W * s)))
        d.polygon([P(*p) for p in arrow_head(cx, cy, ARC_R, a1)], fill=255)
    grad = gradient_image(big, s).resize((big, big))
    # The gradient was laid out in viewport units; re-lay it for the zoomed mark.
    grad = Image.new("RGB", (big, big))
    gp = grad.load()
    x0, y0 = P(26, 30)
    x1, y1 = P(82, 78)
    dx, dy = x1 - x0, y1 - y0
    den = dx * dx + dy * dy
    for y in range(0, big):
        for x in range(0, big):
            tt = max(0.0, min(1.0, ((x - x0) * dx + (y - y0) * dy) / den))
            gp[x, y] = tuple(int(MINT[i] + (CYAN[i] - MINT[i]) * tt) for i in range(3))
    img.paste(grad, (0, 0), mask)
    if shape == "circle":
        clip = Image.new("L", (big, big), 0)
        ImageDraw.Draw(clip).ellipse([0, 0, big - 1, big - 1], fill=255)
        img.putalpha(Image.composite(img.getchannel("A"), clip, clip))
    return img.resize((size_px, size_px), Image.LANCZOS)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    res = os.path.join(root, "app/src/main/res")
    colour, mono = vectors()
    open(os.path.join(res, "drawable/ic_launcher_foreground.xml"), "w").write(colour)
    open(os.path.join(res, "drawable/ic_launcher_monochrome.xml"), "w").write(mono)
    for folder, px in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        d = os.path.join(res, "mipmap-" + folder)
        render(px, "square").save(os.path.join(d, "ic_launcher.webp"), "WEBP", lossless=True)
        render(px, "circle").save(os.path.join(d, "ic_launcher_round.webp"), "WEBP", lossless=True)
    render(512, "square").save(os.path.join(root, "branding/icone_jr_c50d_sync.png"))
    print("ok")


if __name__ == "__main__":
    main()
